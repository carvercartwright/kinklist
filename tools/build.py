"""Run after editing classic.txt, detailed.txt or plsno.txt:  python tools/build.py

1. Copies classic.txt into the list embedded in index.html.
2. Updates kinklist-order.js, which fixes each rating's position in shared links.
   Positions are only ever added at the end, so links made earlier keep their meaning
   when items are added, removed or moved. A removed item keeps its position, unused.
3. Reads tools/merges.txt, which names removed duplicates and the item that replaces each,
   so a rating given to the removed one carries over when the kept one has none.

To rename an item without losing its ratings in old links, pass the old and new keys:
    python tools/build.py --rename "classic|Pain|Hot Wax|Giving=classic|Pain|Hot oil / wax|Giving"
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LISTS = ("classic", "detailed", "plsno")
ORDER_FILE = ROOT / "kinklist-order.js"
MERGES_FILE = ROOT / "tools" / "merges.txt"


def keys(text):
    """Every rating in display order, as 'Category\\nItem\\nColumn'. Mirrors parseKinksText."""
    cats, cat = {}, None
    for line in text.replace("\r", "").split("\n"):
        line = line.strip()
        if not line:
            continue
        rest = line[1:].strip()
        if line[0] == "#":
            cat = {"fields": [], "kinks": []} if rest else None
            if cat is not None:
                cats[rest] = cat
        elif cat is None:
            continue
        elif line[0] == "(":
            cat["fields"] = [f.strip() for f in re.sub(r"\)$", "", rest).split(",") if f.strip()]
        elif line[0] == "*":
            cat["kinks"].append(rest)
    return ["\n".join((name, kink, field)) for name, cat in cats.items() for kink in cat["kinks"] for field in cat["fields"]]


def read_order():
    if not ORDER_FILE.exists():
        return {}
    match = re.search(r"^var KinklistOrder = (.*);$", ORDER_FILE.read_text(encoding="utf-8"), re.M)
    return json.loads(match.group(1))


def merges(order):
    """[[from position, to position], ...] per list, from tools/merges.txt."""
    out = {name: [] for name in LISTS}
    if not MERGES_FILE.exists():
        return out
    for line in MERGES_FILE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        left, right = (side.strip() for side in line.split("=>"))
        name, old_cat, old_item = (part.strip() for part in left.split("|"))
        new_cat, new_item = (part.strip() for part in right.split("|"))
        slots = order[name]
        old = [i for i, key in enumerate(slots) if key.startswith(old_cat + "\n" + old_item + "\n")]
        new = [i for i, key in enumerate(slots) if key.startswith(new_cat + "\n" + new_item + "\n")]
        assert old and new, "merges.txt: unknown item in: " + line
        if len(old) == len(new):
            pairs = zip(old, new)
        elif len(old) == 1:
            pairs = ((old[0], slot) for slot in new)
        else:
            pairs = ((slot, new[0]) for slot in old)
        out[name].extend([a, b] for a, b in pairs)
    return out


def main():
    order = read_order()

    for arg in sys.argv[1:]:
        if arg == "--rename":
            continue
        old, new = arg.split("=", 1)
        name, old_key = old.split("|", 1)
        new_key = new.split("|", 1)[1]
        slots = order[name]
        slots[slots.index(old_key.replace("|", "\n"))] = new_key.replace("|", "\n")
        print("renamed in", name + ":", old_key, "->", new_key)

    for name in LISTS:
        text = (ROOT / (name + ".txt")).read_text(encoding="utf-8")
        current = keys(text)
        assert len(current) == len(set(current)), name + ".txt lists the same item twice in one category"
        known = order.setdefault(name, [])
        seen = set(known)
        added = [k for k in current if k not in seen]
        known.extend(added)
        unused = len(set(known) - set(current))
        print(f"{name}: {len(known)} positions, {len(added)} new, {unused} unused")

    merged = merges(order)
    print("merges:", ", ".join(f"{name} {len(pairs)}" for name, pairs in merged.items()))

    ORDER_FILE.write_text(
        "// Generated by tools/build.py. Do not edit by hand.\n"
        "// Each rating's position in shared links; only ever appended to.\n"
        "var KinklistOrder = " + json.dumps(order, ensure_ascii=False, separators=(",", ":")) + ";\n"
        "// [from, to] positions: a removed duplicate's rating carries over to the item that replaced it.\n"
        "var KinklistMerge = " + json.dumps(merged, separators=(",", ":")) + ";\n",
        encoding="utf-8", newline="\n")

    page = ROOT / "index.html"
    html = page.read_text(encoding="utf-8")
    classic = (ROOT / "classic.txt").read_text(encoding="utf-8").replace("\r", "").strip()
    assert "<" not in classic, "classic.txt must not contain '<'"
    new_html, count = re.subn(r'(<textarea id="Kinks"[^>]*>\n).*?(\n\s*</textarea>)',
                              lambda m: m.group(1) + classic + m.group(2), html, flags=re.S)
    assert count == 1, "could not find the embedded list in index.html"
    page.write_text(new_html, encoding="utf-8", newline="\n")
    print("index.html: embedded list synced")

    # Stamp each script and stylesheet address with a version taken from its contents,
    # so a browser never pairs a new page with an old cached file.
    def stamp(match):
        data = (ROOT / match.group(2)).read_bytes().replace(b"\r\n", b"\n")
        return match.group(1) + match.group(2) + "?v=" + hashlib.sha1(data).hexdigest()[:8] + '"'

    for name in ("index.html", "compare.html"):
        page = ROOT / name
        html = page.read_text(encoding="utf-8")
        html = re.sub(r'((?:src|href)=")(kinklist[\w-]*\.(?:js|css)|compare\.js)(?:\?v=\w+)?"', stamp, html)
        page.write_text(html, encoding="utf-8", newline="\n")
    print("asset versions stamped")


if __name__ == "__main__":
    main()
