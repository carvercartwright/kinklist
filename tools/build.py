"""Run after editing classic.txt, detailed.txt or plsno.txt:  python tools/build.py

1. Copies classic.txt into the list embedded in index.html.
2. Updates kinklist-order.js, which fixes each rating's position in shared links.
   Positions are only ever added at the end, so links made earlier keep their meaning
   when items are added, removed or moved. A removed item keeps its position, unused.

To rename an item without losing its ratings in old links, pass the old and new keys:
    python tools/build.py --rename "classic|Pain|Hot Wax|Giving=classic|Pain|Hot oil / wax|Giving"
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LISTS = ("classic", "detailed", "plsno")
ORDER_FILE = ROOT / "kinklist-order.js"


def keys(text):
    """Every rating in display order, as 'Category\\nItem\\nColumn'. Mirrors parseKinksText."""
    cats, cat = {}, None
    for line in text.replace("\r", "").split("\n"):
        line = line.strip()
        if not line:
            continue
        rest = line[1:].strip()
        if line[0] == "#":
            cat = {"fields": [], "kinks": []} if rest else None
            if cat is not None:
                cats[rest] = cat
        elif cat is None:
            continue
        elif line[0] == "(":
            cat["fields"] = [f.strip() for f in re.sub(r"\)$", "", rest).split(",") if f.strip()]
        elif line[0] == "*":
            cat["kinks"].append(rest)
    return ["\n".join((name, kink, field)) for name, cat in cats.items() for kink in cat["kinks"] for field in cat["fields"]]


def main():
    order = {}
    if ORDER_FILE.exists():
        order = json.loads(ORDER_FILE.read_text(encoding="utf-8").split("=", 1)[1].rstrip().rstrip(";"))

    for arg in sys.argv[1:]:
        if arg == "--rename":
            continue
        old, new = arg.split("=", 1)
        name, old_key = old.split("|", 1)
        new_key = new.split("|", 1)[1]
        slots = order[name]
        slots[slots.index(old_key.replace("|", "\n"))] = new_key.replace("|", "\n")
        print("renamed in", name + ":", old_key, "->", new_key)

    for name in LISTS:
        text = (ROOT / (name + ".txt")).read_text(encoding="utf-8")
        known = order.setdefault(name, [])
        seen = set(known)
        added = [k for k in keys(text) if k not in seen]
        known.extend(dict.fromkeys(added))
        unused = len(set(known) - set(keys(text)))
        print(f"{name}: {len(known)} positions, {len(added)} new, {unused} unused")

    ORDER_FILE.write_text(
        "// Generated by tools/build.py. Fixes each rating's position in shared links; only ever appended to.\n"
        "var KinklistOrder = " + json.dumps(order, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8", newline="\n")

    page = ROOT / "index.html"
    html = page.read_text(encoding="utf-8")
    classic = (ROOT / "classic.txt").read_text(encoding="utf-8").replace("\r", "").strip()
    assert "<" not in classic, "classic.txt must not contain '<'"
    new_html, count = re.subn(r'(<textarea id="Kinks"[^>]*>\n).*?(\n\s*</textarea>)',
                              lambda m: m.group(1) + classic + m.group(2), html, flags=re.S)
    assert count == 1, "could not find the embedded list in index.html"
    page.write_text(new_html, encoding="utf-8", newline="\n")
    print("index.html: embedded list synced")


if __name__ == "__main__":
    main()
